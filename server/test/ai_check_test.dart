import 'package:famcoin_server/ai_check.dart';
import 'package:test/test.dart';

const _context = <String, dynamic>{
  'today': '2026-10-02',
  'dailyLimit': {'perDay': 5000, 'overspentOnPreviousDays': 293, 'spentToday': 3180, 'availableToday': 1527},
  'bankDebts': {'totalDebt': 1236828, 'monthlyPayments': 80000},
  'monthEndBalanceForecast': {'estimate': -264090, 'rangeLow': -297741, 'rangeHigh': -230439},
  'expenseByCategory': [
    {'name': 'Продукты', 'amount': 65000},
    {'name': 'Кафе', 'amount': 13000},
    {'name': 'Транспорт', 'amount': 9000},
  ],
  'plannedPurchases': [
    {'name': 'Колёса', 'amount': 100000, 'toSavePerMonth': 16700},
  ],
  'operationsEarlier': [
    {'date': '2026-09-12', 'amount': 4707.5, 'note': 'Ремонт 30000, стартер'},
  ],
};

List<String> _check(String answer, {List<String> texts = const []}) => unverifiedAmounts(answer, context: _context, texts: texts);

void main() {
  test('суммы из данных, их сумма и разность — подтверждаются', () {
    expect(_check('Считается так: 5 000 ₸ лимит − 293 ₸ перерасход − 3 180 ₸ сегодня = 1 527 ₸. Без этих 293 ₸ было бы 1 820 ₸.'), isEmpty);
    expect(_check('По данным к концу месяца не хватит 264 090 ₸; сценарии — от 230 439 до 297 741 ₸.'), isEmpty);
    expect(_check('До лимита осталось 1 527 тенге, это 0 ₸ сверх плана.'), isEmpty);
    expect(_check('Все три категории вместе — 87 000 ₸.'), isEmpty, reason: 'итог по списку из данных');
    expect(_check('На ремонт ушло 30 000 ₸ — так написано в заметке.'), isEmpty, reason: 'число из заметки человека');
    expect(_check('Операция на 4 708 ₸ была 12 сентября.'), isEmpty, reason: 'копейки округлены');
  });

  test('суммы, которых в данных нет, — помечаются', () {
    expect(_check('Вы потратили 12 345 ₸ на кафе.'), ['12 345 ₸']);
    expect(_check('Сценарии — от 230 439 до 300 000 ₸, а в прошлом году 111 222.'), ['300 000 ₸', '111 222']);
    expect(_check('За 3 месяца по 16 700 ₸ накопится 50 100 ₸.'), ['50 100 ₸'], reason: 'умножение — собственный расчёт модели');
    expect(_check('Лимит 5 000 ₸, значит за 30 дней 150 000 ₸, а 150 000 ₸ — это немало.'), ['150 000 ₸'], reason: 'без повторов');
  });

  test('приблизительные суммы и суммы словами', () {
    expect(_check('Долг по банкам — около 1,2 млн ₸.'), isEmpty);
    expect(_check('Долг по банкам — 1,24 млн тенге.'), isEmpty);
    expect(_check('Долг по банкам — 5 млн ₸.'), ['5 млн ₸']);
    expect(_check('Платёж — 80 тыс. ₸ в месяц, это примерно 81 000 ₸ с комиссией.'), isEmpty, reason: '«примерно» допускает 3 %');
    expect(_check('Платёж — примерно 700 000 ₸.'), ['700 000 ₸']);
  });

  test('числа из вопроса и прошлых реплик считаются известными', () {
    expect(_check('Телефон за 250 000 ₸ плюс колёса за 100 000 ₸ — это 350 000 ₸.', texts: ['Хочу купить телефон за 250 тысяч']), isEmpty);
    expect(_check('Телефон за 250 000 ₸.'), ['250 000 ₸']);
  });

  test('проверка — сеть, а не доказательство: круглое число может совпасть с суммой двух чисел из данных', () {
    // 35 000 = 30 000 (из заметки) + 5 000 (лимит): проверка такое пропустит.
    expect(_check('В неделю выходит 35 000 ₸.'), isEmpty);
  });

  test('проценты, даты, годы и количества — не суммы', () {
    expect(_check('Это 1 350 % от дохода, 28 сентября 2026 года было 3 операции, прошло 15 дней.'), isEmpty);
  });
}
