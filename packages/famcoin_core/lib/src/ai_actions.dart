/// Оставляет только известные id, без повторов, не больше [limit].
List<String> knownAiActions(Object? raw, {int limit = 2}) {
  if (raw is! List) return const [];
  final out = <String>[];
  for (final e in raw) {
    if (e is String && aiActions.containsKey(e) && !out.contains(e)) out.add(e);
    if (out.length >= limit) break;
  }
  return out;
}
